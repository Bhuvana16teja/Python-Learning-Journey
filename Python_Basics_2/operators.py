# Given two integer variables x and y, perform the following operations:
# p = x + y  (Addition)
# q = x - y  (Subtraction)
# r = x * y  (Multiplication)
# s = x / y  (Integer Division)
# t = x % y  (Modulo)
# Print all the results separated by spaces.

x = int(input())
y = int(input())

p = x + y
q = x - y
r = x * y
s = x // y
t = x % y

print(p, q, r, s, t)
